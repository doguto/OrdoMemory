using System.Linq;
using System.Text;

namespace OrdoMemory.Generator
{
    static class TableEmitter
    {
        public static string Emit(TableModel m)
        {
            var w = new Writer();
            var row = m.RowFullName;
            var pk = m.PkType;
            var store = $"global::OrdoMemory.RowStore<{row}, {pk}, {m.PkTraits}>";

            w.Line("// <auto-generated/>");
            w.Line("#nullable disable");
            w.Line("#pragma warning disable");
            w.Line();

            if (m.Namespace != null)
            {
                w.Line($"namespace {m.Namespace}");
                w.Open();
            }

            if (m.GenerateConstructor) EmitConstructor(w, m);

            w.Line($"{m.Accessibility} sealed partial class {m.TableName}");
            w.Open();
            w.Line($"public const {pk} InvalidPk = 0;");
            w.Line($"public const int SlotBits = {m.SlotBits};");
            w.Line();
            w.Line($"static readonly {row} __notFound = default;");
            w.Line();
            w.Line($"readonly {store} __store;");
            foreach (var k in m.Keys) w.Line($"readonly {IndexType(m, k)} {k.IndexField};");
            w.Line();

            w.Line($"public {m.TableName}(int capacity = 0)");
            w.Open();
            w.Line($"__store = new {store}(capacity, SlotBits);");
            foreach (var k in m.Keys)
            {
                w.Line(k.Hash
                    ? $"{k.IndexField} = new {IndexType(m, k)}();"
                    : $"{k.IndexField} = new {IndexType(m, k)}({(k.Unique ? "true" : "false")});");
            }

            w.Close();
            w.Line();
            w.Line("public int Count => __store.Count;");
            w.Line();
            w.Line("public int Capacity => __store.Capacity;");
            w.Line();

            EmitInsert(w, m);
            EmitBulkInsert(w, m);
            EmitFind(w, m);
            EmitUpdate(w, m);
            EmitRemove(w, m);

            w.Line($"public {store}.AllEnumerable All() => __store.All();");
            w.Line();

            foreach (var k in m.Keys) EmitKeyQueries(w, m, k, store);

            w.Line("public void TrimExcess()");
            w.Open();
            w.Line("__store.TrimExcess();");
            foreach (var k in m.Keys) w.Line($"{k.IndexField}.TrimExcess();");
            w.Close();

            w.Close();
            if (m.Namespace != null) w.Close();
            return w.ToString();
        }

        static string IndexType(TableModel m, KeyModel k)
        {
            if (!k.Hash) return $"global::OrdoMemory.OrderedIndex<{k.KeyType}, {k.KeyTraits}, {m.PkType}, {m.PkTraits}>";
            return k.Unique
                ? $"global::OrdoMemory.HashUniqueIndex<{k.KeyType}, {m.PkType}>"
                : $"global::OrdoMemory.HashMultiIndex<{k.KeyType}, {m.PkType}>";
        }

        static string InnerEnumeratorType(TableModel m, KeyModel k)
        {
            if (!k.Hash) return IndexType(m, k) + ".RangeEnumerator";
            return IndexType(m, k) + (k.Unique ? ".SingleEnumerator" : ".Enumerator");
        }

        static string Conv(KeyModel k, string expr)
        {
            return string.Format(k.Convert, expr);
        }

        static void EmitConstructor(Writer w, TableModel m)
        {
            w.Line($"partial struct {m.RowName}");
            w.Open();
            var parameters = string.Join(", ", m.Fields.Select(f => $"{f.Type} {f.ParameterName}"));
            w.Line($"public {m.RowName}({parameters})");
            w.Open();
            foreach (var f in m.Fields) w.Line($"this.{f.Name} = {f.ParameterName};");
            w.Close();
            w.Close();
            w.Line();
        }

        static void EmitInsert(Writer w, TableModel m)
        {
            w.Line($"public bool TryInsert(in {m.RowFullName} row, out {m.PkType} pk)");
            w.Open();
            var uniques = m.Keys.Where(k => k.Unique).ToList();
            if (uniques.Count > 0)
            {
                var cond = string.Join(" || ", uniques.Select(k => $"{k.IndexField}.ContainsKey({Conv(k, "row." + k.Field.Name)})"));
                w.Line($"if ({cond} || !__store.TryReserve(1))");
            }
            else
            {
                w.Line("if (!__store.TryReserve(1))");
            }

            w.Open();
            w.Line("pk = InvalidPk;");
            w.Line("return false;");
            w.Close();
            w.Line();
            w.Line("pk = __store.Store(in row);");
            foreach (var k in m.Keys) w.Line($"{k.IndexField}.Insert({Conv(k, "row." + k.Field.Name)}, pk);");
            w.Line("return true;");
            w.Close();
            w.Line();
        }

        static void EmitBulkInsert(Writer w, TableModel m)
        {
            var row = m.RowFullName;
            var pk = m.PkType;
            w.Line("// 払い出した PK は pks の先頭から書き込む. 容量の不足や Unique の重複がある場合は何も挿入しない.");
            w.Line($"public bool TryBulkInsert(global::System.ReadOnlySpan<{row}> rows, global::System.Span<{pk}> pks)");
            w.Open();
            w.Line("if (pks.Length < rows.Length) throw new global::System.ArgumentException(\"pks is shorter than rows.\", nameof(pks));");
            w.Line("var n = rows.Length;");
            w.Line("if (n == 0) return true;");
            w.Line("if (!__store.TryReserve(n)) return false;");
            w.Line();
            w.Line("for (var i = 0; i < n; i++) pks[i] = __store.Store(in rows[i]);");
            w.Line($"global::System.ReadOnlySpan<{pk}> stored = pks.Slice(0, n);");

            for (var i = 0; i < m.Keys.Count; i++)
            {
                var k = m.Keys[i];
                var pool = $"global::System.Buffers.ArrayPool<{k.KeyType}>.Shared";
                w.Line();
                w.Line($"var keys{i} = {pool}.Rent(n);");
                w.Line($"bool ok{i};");
                w.Line("try");
                w.Open();
                w.Line($"for (var i = 0; i < n; i++) keys{i}[i] = {Conv(k, "rows[i]." + k.Field.Name)};");
                w.Line($"ok{i} = {k.IndexField}.AddRange(new global::System.ReadOnlySpan<{k.KeyType}>(keys{i}, 0, n), stored);");
                w.Close();
                w.Line("finally");
                w.Open();
                w.Line($"{pool}.Return(keys{i}{(k.KeyIsReference ? ", true" : "")});");
                w.Close();
                w.Line();
                w.Line($"if (!ok{i})");
                w.Open();
                w.Line($"__RollbackBulk(rows, stored, {i});");
                w.Line("return false;");
                w.Close();
            }

            w.Line();
            w.Line("return true;");
            w.Close();
            w.Line();

            w.Line($"void __RollbackBulk(global::System.ReadOnlySpan<{row}> rows, global::System.ReadOnlySpan<{pk}> pks, int addedIndexes)");
            w.Open();
            if (m.Keys.Count > 0)
            {
                w.Line("for (var i = 0; i < rows.Length; i++)");
                w.Open();
                for (var i = 0; i < m.Keys.Count; i++)
                {
                    var k = m.Keys[i];
                    w.Line($"if (addedIndexes > {i}) {k.IndexField}.Remove({Conv(k, "rows[i]." + k.Field.Name)}, pks[i]);");
                }

                w.Close();
                w.Line();
            }

            w.Line("for (var i = 0; i < rows.Length; i++) __store.RemoveAt(__store.Count - 1);");
            w.Close();
            w.Line();
        }

        static void EmitFind(Writer w, TableModel m)
        {
            var row = m.RowFullName;
            var pk = m.PkType;
            w.Line($"public bool Contains({pk} pk) => __store.TryGetIndex(pk, out _);");
            w.Line();
            w.Line($"public bool TryFind({pk} pk, out {row} row)");
            w.Open();
            w.Line("if (__store.TryGetIndex(pk, out var index))");
            w.Open();
            w.Line("row = __store.RowAt(index);");
            w.Line("return true;");
            w.Close();
            w.Line();
            w.Line("row = default;");
            w.Line("return false;");
            w.Close();
            w.Line();
            w.Line("// 見つからない場合は found = false とし、default への参照を返す.");
            w.Line("// 参照は次の Insert / BulkInsert / Remove / TrimExcess まで有効.");
            w.Line($"public ref readonly {row} FindRef({pk} pk, out bool found)");
            w.Open();
            w.Line("found = __store.TryGetIndex(pk, out var index);");
            w.Line("if (found) return ref __store.RowAt(index);");
            w.Line("return ref __notFound;");
            w.Close();
            w.Line();
        }

        static void EmitUpdate(Writer w, TableModel m)
        {
            var parameters = string.Join(", ", m.Fields.Select(f => $"global::OrdoMemory.Optional<{f.Type}> {f.ParameterName} = default"));
            w.Line("// 指定した項目だけを更新する. Unique な SecondaryKey が他の Record と重なる場合は何もせず false を返す.");
            w.Line($"public bool Update({m.PkType} pk, {parameters})");
            w.Open();
            w.Line("if (!__store.TryGetIndex(pk, out var __index)) return false;");
            w.Line();
            w.Line("ref var __current = ref __store.RowAt(__index);");
            var args = string.Join(", ", m.Fields.Select(f => $"{f.ParameterName}.OrElse(__current.{f.Name})"));
            w.Line($"var __next = new {m.RowFullName}({args});");

            for (var i = 0; i < m.Keys.Count; i++)
            {
                var k = m.Keys[i];
                w.Line($"var __oldKey{i} = {Conv(k, "__current." + k.Field.Name)};");
                w.Line($"var __newKey{i} = {Conv(k, "__next." + k.Field.Name)};");
                w.Line($"var __changed{i} = !global::System.Collections.Generic.EqualityComparer<{k.KeyType}>.Default.Equals(__oldKey{i}, __newKey{i});");
            }

            var uniques = Enumerable.Range(0, m.Keys.Count).Where(i => m.Keys[i].Unique).ToList();
            if (uniques.Count > 0)
            {
                var cond = string.Join(" || ", uniques.Select(i => $"(__changed{i} && {m.Keys[i].IndexField}.ContainsKey(__newKey{i}))"));
                w.Line($"if ({cond}) return false;");
            }

            for (var i = 0; i < m.Keys.Count; i++)
            {
                var k = m.Keys[i];
                w.Line($"if (__changed{i})");
                w.Open();
                w.Line($"{k.IndexField}.Remove(__oldKey{i}, pk);");
                w.Line($"{k.IndexField}.Insert(__newKey{i}, pk);");
                w.Close();
            }

            w.Line();
            w.Line("__current = __next;");
            if (m.Keys.Count > 0)
            {
                // 索引の構造が変わった場合は、索引を辿っている列挙子を無効にする.
                var any = string.Join(" || ", Enumerable.Range(0, m.Keys.Count).Select(i => $"__changed{i}"));
                w.Line($"if ({any}) __store.Touch();");
            }

            w.Line("return true;");
            w.Close();
            w.Line();
        }

        static void EmitRemove(Writer w, TableModel m)
        {
            w.Line("// 末尾の Record を空いた位置へ移す. 移した Record への参照は無効になる.");
            w.Line($"public bool Remove({m.PkType} pk)");
            w.Open();
            w.Line("if (!__store.TryGetIndex(pk, out var index)) return false;");
            w.Line();
            if (m.Keys.Count > 0)
            {
                w.Line("ref readonly var row = ref __store.RowAt(index);");
                foreach (var k in m.Keys) w.Line($"{k.IndexField}.Remove({Conv(k, "row." + k.Field.Name)}, pk);");
            }

            w.Line("__store.RemoveAt(index);");
            w.Line("return true;");
            w.Close();
            w.Line();
        }

        static void EmitKeyQueries(Writer w, TableModel m, KeyModel k, string store)
        {
            var row = m.RowFullName;
            var name = k.Field.Name;
            var type = k.Field.Type;
            var idx = k.IndexField;
            var enumerable = $"{store}.IndexEnumerable<{InnerEnumeratorType(m, k)}>";
            var first = k.Unique ? $"TryFindBy{name}" : $"TryFindFirstBy{name}";

            if (!k.Unique) w.Line("// 索引上の先頭. Ordered では SecondaryKey が等しいものの中で PK の昇順の先頭.");
            w.Line($"public bool {first}({type} key, out {row} row)");
            w.Open();
            w.Line($"if ({idx}.TryGetFirst({Conv(k, "key")}, out var pk))");
            w.Open();
            w.Line("row = __store.RowAt(__store.IndexOf(pk));");
            w.Line("return true;");
            w.Close();
            w.Line();
            w.Line("row = default;");
            w.Line("return false;");
            w.Close();
            w.Line();

            var firstPk = k.Unique ? $"TryFindPkBy{name}" : $"TryFindFirstPkBy{name}";
            w.Line($"public bool {firstPk}({type} key, out {m.PkType} pk) => {idx}.TryGetFirst({Conv(k, "key")}, out pk);");
            w.Line();

            if (!k.Unique)
            {
                w.Line($"public {enumerable} FindAllBy{name}({type} key) => __store.Enumerate({idx}.Equal({Conv(k, "key")}));");
                w.Line();
            }

            if (!k.Hash)
            {
                w.Line("// min 以上 max 以下を SecondaryKey の昇順で返す.");
                w.Line($"public {enumerable} FindRangeBy{name}({type} min, {type} max) => __store.Enumerate({idx}.Range({Conv(k, "min")}, {Conv(k, "max")}));");
                w.Line();
            }
        }

        sealed class Writer
        {
            readonly StringBuilder sb = new StringBuilder();
            int indent;

            public void Line(string text = "")
            {
                if (text.Length > 0) sb.Append(' ', indent * 4).Append(text);
                sb.Append('\n');
            }

            public void Open()
            {
                Line("{");
                indent++;
            }

            public void Close()
            {
                indent--;
                Line("}");
            }

            public override string ToString() => sb.ToString();
        }
    }
}
