using System.Linq;
using OrdoMemory.Generator.Models;
using static OrdoMemory.Generator.Emitting.TemplateFunctions;

namespace OrdoMemory.Generator.Emitting
{
    internal static class TableEmitter
    {
        public static string Emit(TableModel model)
        {
            var rowType = model.RowFullName;
            var primaryKeyType = model.PrimaryKeyType;
            var storeType = $"global::OrdoMemory.RowStore<{rowType}, {primaryKeyType}, {model.PrimaryKeyTraits}>";

            var table = Render($$"""
                                 {{EmitRowMembers(model)}}

                                 {{model.Accessibility}} sealed partial class {{model.TableName}}
                                 {
                                     public const {{primaryKeyType}} InvalidPrimaryKey = 0;
                                     public const int SlotBits = {{model.SlotBits}};
                                 
                                     static readonly {{rowType}} __notFound = default;
                                 
                                     readonly {{storeType}} __store;
                                     {{Each(model.Keys, key => $"readonly {IndexType(model, key)} {key.IndexField};")}}
                                 
                                     public {{model.TableName}}(int capacity = 0)
                                     {
                                         __store = new {{storeType}}(capacity, SlotBits);
                                         {{Each(model.Keys, key => $"{key.IndexField} = new {IndexType(model, key)}({IndexConstructorArguments(key)});")}}
                                     }
                                 
                                     public int Count => __store.Count;
                                 
                                     public int Capacity => __store.Capacity;
                                 
                                     {{EmitInsert(model)}}
                                 
                                     {{EmitBulkInsert(model)}}
                                 
                                     {{EmitFind(model)}}
                                 
                                     {{EmitUpdate(model)}}
                                 
                                     {{EmitRemove(model)}}
                                 
                                     public {{storeType}}.AllEnumerable All() => __store.All();
                                 
                                     {{Each(model.Keys, key => EmitKeyQueries(model, key, storeType), "\n\n")}}
                                 
                                     public void TrimExcess()
                                     {
                                         __store.TrimExcess();
                                         {{Each(model.Keys, key => $"{key.IndexField}.TrimExcess();")}}
                                     }
                                 }
                                 """);

            var body = model.NamespaceName == null
                ? table
                : Render($$"""
                           namespace {{model.NamespaceName}}
                           {
                               {{table}}
                           }
                           """);

            return Render($$"""
                            // <auto-generated/>
                            #nullable disable
                            #pragma warning disable

                            {{body}}
                            """) + "\n";
        }

        static string EmitRowMembers(TableModel model)
        {
            var parameters = string.Join(", ", model.Fields.Select(field => $"{field.Type} {field.ParameterName}"));
            var publicConstructor = If(model.GenerateConstructor, Render($$"""
                                                                           public {{model.RowName}}({{parameters}})
                                                                           {
                                                                               this.{{model.PrimaryKeyField}} = default;
                                                                               {{Each(model.Fields, field => $"this.{field.Name} = {field.ParameterName};")}}
                                                                           }
                                                                           """));

            // 主キーは Store で払い出されるまで決まらないため、払い出した後に主キーを差し込んだコピーを作る.
            // Update もこのコンストラクタを使う. 利用者が同じ型の並びのコンストラクタを定義していても
            // 引数の位置で呼び違えないよう、RowInitTag を取る専用のコンストラクタにする.
            // Row が readonly struct でなくても隠れたコピーが起きないよう、生成するメンバーには readonly を付ける
            var thisArguments = string.Join(", ", model.Fields.Select(field => $"this.{field.Name}"));
            var rowInterface = $"global::OrdoMemory.IRow<{model.RowName}, {model.PrimaryKeyType}>";
            return Render($$"""
                            partial struct {{model.RowName}} : {{rowInterface}}
                            {
                                readonly {{model.PrimaryKeyType}} {{rowInterface}}.PrimaryKey => {{model.PrimaryKeyField}};

                                readonly {{model.RowName}} {{rowInterface}}.WithPrimaryKey({{model.PrimaryKeyType}} primaryKey) => new {{model.RowName}}(default(global::OrdoMemory.RowInitTag), primaryKey, {{thisArguments}});

                                {{publicConstructor}}

                                internal {{model.RowName}}(global::OrdoMemory.RowInitTag __tag, {{model.PrimaryKeyType}} primaryKey, {{parameters}})
                                {
                                    this.{{model.PrimaryKeyField}} = primaryKey;
                                    {{Each(model.Fields, field => $"this.{field.Name} = {field.ParameterName};")}}
                                }
                            }
                            """);
        }

        static string EmitInsert(TableModel model)
        {
            var duplicateConditions = model.Keys
                                           .Where(key => key.Unique)
                                           .Select(key => $"{key.IndexField}.ContainsKey({ConvertKey(key, "row." + key.Field.Name)})")
                                           .ToList();

            var rejectDuplicate = If(duplicateConditions.Count > 0, Render($$"""
                                                                           if ({{string.Join(" || ", duplicateConditions)}})
                                                                           {
                                                                               primaryKey = InvalidPrimaryKey;
                                                                               result = global::OrdoMemory.InsertResult.Duplicate;
                                                                               return false;
                                                                           }
                                                                           """));

            return Render($$"""
                            public bool TryInsert(in {{model.RowFullName}} row, out {{model.PrimaryKeyType}} primaryKey) => TryInsert(in row, out primaryKey, out _);

                            public bool TryInsert(in {{model.RowFullName}} row, out {{model.PrimaryKeyType}} primaryKey, out global::OrdoMemory.InsertResult result)
                            {
                                {{rejectDuplicate}}
                            
                                if (!__store.TryReserve(1))
                                {
                                    primaryKey = InvalidPrimaryKey;
                                    result = global::OrdoMemory.InsertResult.Full;
                                    return false;
                                }
                            
                                primaryKey = __store.Store(in row);
                                {{Each(model.Keys, key => $"{key.IndexField}.Insert({ConvertKey(key, "row." + key.Field.Name)}, primaryKey);")}}
                                result = global::OrdoMemory.InsertResult.Success;
                                return true;
                            }
                            """);
        }

        static string EmitBulkInsert(TableModel model)
        {
            var rowType = model.RowFullName;
            var primaryKeyType = model.PrimaryKeyType;
            var keyIndices = Enumerable.Range(0, model.Keys.Count).ToList();

            var removeFromIndexes = If(model.Keys.Count > 0, Render($$"""
                                                                      for (var i = 0; i < rows.Length; i++)
                                                                      {
                                                                          {{Each(keyIndices, keyIndex => EmitRollbackIndex(model, keyIndex))}}
                                                                      }
                                                                      """));

            return Render($$"""
                            public bool TryBulkInsert(global::System.ReadOnlySpan<{{rowType}}> rows, global::System.Span<{{primaryKeyType}}> primaryKeys) => TryBulkInsert(rows, primaryKeys, out _);

                            public bool TryBulkInsert(global::System.ReadOnlySpan<{{rowType}}> rows, global::System.Span<{{primaryKeyType}}> primaryKeys, out global::OrdoMemory.InsertResult result)
                            {
                                if (primaryKeys.Length < rows.Length) throw new global::System.ArgumentException("primaryKeys is shorter than rows.", nameof(primaryKeys));
                                result = global::OrdoMemory.InsertResult.Success;
                                var rowCount = rows.Length;
                                if (rowCount == 0) return true;
                                if (!__store.TryReserve(rowCount))
                                {
                                    result = global::OrdoMemory.InsertResult.Full;
                                    return false;
                                }
                            
                                for (var i = 0; i < rowCount; i++)
                                {
                                    primaryKeys[i] = __store.Store(in rows[i]);
                                }

                                global::System.ReadOnlySpan<{{primaryKeyType}}> stored = primaryKeys.Slice(0, rowCount);
                            
                                {{Each(keyIndices, keyIndex => EmitBulkInsertIndex(model, keyIndex), "\n\n")}}
                            
                                return true;
                            }

                            void __RollbackBulkInsert(global::System.ReadOnlySpan<{{rowType}}> rows, global::System.ReadOnlySpan<{{primaryKeyType}}> primaryKeys, int addedIndexes)
                            {
                                {{removeFromIndexes}}
                            
                                for (var i = 0; i < rows.Length; i++) __store.Remove(__store.Count - 1);
                            }
                            """);
        }

        static string EmitBulkInsertIndex(TableModel model, int keyIndex)
        {
            var key = model.Keys[keyIndex];
            var pool = $"global::System.Buffers.ArrayPool<{key.KeyType}>.Shared";
            return Render($$"""
                            var keys{{keyIndex}} = {{pool}}.Rent(rowCount);
                            bool added{{keyIndex}};
                            try
                            {
                                for (var i = 0; i < rowCount; i++) keys{{keyIndex}}[i] = {{ConvertKey(key, "rows[i]." + key.Field.Name)}};
                                added{{keyIndex}} = {{key.IndexField}}.AddRange(new global::System.ReadOnlySpan<{{key.KeyType}}>(keys{{keyIndex}}, 0, rowCount), stored);
                            }
                            finally
                            {
                                {{pool}}.Return(keys{{keyIndex}}{{If(key.KeyIsReference, ", true")}});
                            }

                            if (!added{{keyIndex}})
                            {
                                __RollbackBulkInsert(rows, stored, {{keyIndex}});
                                result = global::OrdoMemory.InsertResult.Duplicate;
                                return false;
                            }
                            """);
        }

        static string EmitRollbackIndex(TableModel model, int keyIndex)
        {
            var key = model.Keys[keyIndex];
            return $"if (addedIndexes > {keyIndex}) {key.IndexField}.Remove({ConvertKey(key, "rows[i]." + key.Field.Name)}, primaryKeys[i]);";
        }

        static string EmitFind(TableModel model)
        {
            var rowType = model.RowFullName;
            var primaryKeyType = model.PrimaryKeyType;


            return Render($$"""
                            public bool Contains({{primaryKeyType}} primaryKey) => __store.TryGetIndex(primaryKey, out _);

                            public bool TryFind({{primaryKeyType}} primaryKey, out {{rowType}} row)
                            {
                                if (__store.TryGetIndex(primaryKey, out var index))
                                {
                                    row = __store.GetRowRef(index);
                                    return true;
                                }
                            
                                row = default;
                                return false;
                            }

                            public ref readonly {{rowType}} FindRef({{primaryKeyType}} primaryKey, out bool found)
                            {
                                found = __store.TryGetIndex(primaryKey, out var index);
                                if (found) return ref __store.GetRowRef(index);
                                return ref __notFound;
                            }
                            """);
        }

        static string EmitUpdate(TableModel model)
        {
            var parameters = string.Join(", ", model.Fields.Select(field => $"global::OrdoMemory.Optional<{field.Type}> {field.ParameterName} = default"));
            var arguments = string.Join(", ", model.Fields.Select(NextValue));
            var keyIndices = Enumerable.Range(0, model.Keys.Count).ToList();
            var uniqueKeyIndices = keyIndices.Where(keyIndex => model.Keys[keyIndex].Unique).ToList();
            var conflictCondition = string.Join(" || ", uniqueKeyIndices.Select(keyIndex => $"(__changed{keyIndex} && {model.Keys[keyIndex].IndexField}.ContainsKey(__newKey{keyIndex}))"));
            var anyChangedCondition = string.Join(" || ", keyIndices.Select(keyIndex => $"__changed{keyIndex}"));

            // 新しい値をローカル変数に求めてから、RowInitTag を取る専用のコンストラクタで 1 回だけ作り直す
            var rebuild = Render($$"""
                                   {{Each(model.Fields, field => $"var {NextValue(field)} = {field.ParameterName}.OrElse(__current.{field.Name});")}}
                                   {{Each(keyIndices, keyIndex => EmitApplyKeyChange(model, keyIndex))}}
                                   __current = new {{model.RowFullName}}(default(global::OrdoMemory.RowInitTag), primaryKey, {{arguments}});
                                   {{If(keyIndices.Count > 0, $"if ({anyChangedCondition}) __store.Touch();")}}
                                   return true;
                                   """);

            // readonly のフィールドを変える場合だけ、従来どおり Record 全体を作り直す.
            // それ以外は索引を付け替えた後、指定された readonly でないフィールドだけをその場で書き込む
            var body = rebuild;
            if (model.Fields.Any(field => !field.IsReadOnly))
            {
                var mutableKeyIndices = keyIndices.Where(keyIndex => !model.Keys[keyIndex].Field.IsReadOnly).ToList();
                var rebuildConditions = keyIndices.Where(keyIndex => model.Keys[keyIndex].Field.IsReadOnly).Select(keyIndex => $"__changed{keyIndex}")
                                                  .Concat(model.Fields.Where(field => field.IsReadOnly && !model.Keys.Any(key => key.Field == field)).Select(field => $"{field.ParameterName}.HasValue"))
                                                  .ToList();
                var mutableKeyChanged = string.Join(" || ", mutableKeyIndices.Select(keyIndex => $"__changed{keyIndex}"));
                body = Render($$"""
                                {{If(rebuildConditions.Count > 0, Render($$"""
                                                                           if ({{string.Join(" || ", rebuildConditions)}})
                                                                           {
                                                                               {{rebuild}}
                                                                           }
                                                                           """))}}

                                {{Each(mutableKeyIndices, keyIndex => EmitApplyKeyChange(model, keyIndex))}}
                                {{Each(model.Fields.Where(field => !field.IsReadOnly), field => $"if ({field.ParameterName}.HasValue) __current.{field.Name} = {field.ParameterName}.Value;")}}
                                {{If(mutableKeyIndices.Count > 0, $"if ({mutableKeyChanged}) __store.Touch();")}}
                                return true;
                                """);
            }

            return Render($$"""
                            public bool Update({{model.PrimaryKeyType}} primaryKey, {{parameters}})
                            {
                                if (!__store.TryGetIndex(primaryKey, out var __index)) return false;
                            
                                ref var __current = ref __store.GetRowRef(__index);
                                {{Each(keyIndices, keyIndex => EmitDetectKeyChange(model, keyIndex))}}
                                {{If(uniqueKeyIndices.Count > 0, $"if ({conflictCondition}) return false;")}}
                            
                                {{body}}
                            }
                            """);
        }

        static string NextValue(FieldModel field)
        {
            return "__next_" + field.Name;
        }

        static string EmitDetectKeyChange(TableModel model, int keyIndex)
        {
            var key = model.Keys[keyIndex];
            return Render($$"""
                            var __oldKey{{keyIndex}} = {{ConvertKey(key, "__current." + key.Field.Name)}};
                            var __newKey{{keyIndex}} = {{ConvertKey(key, $"{key.Field.ParameterName}.OrElse(__current.{key.Field.Name})")}};
                            var __changed{{keyIndex}} = !global::System.Collections.Generic.EqualityComparer<{{key.KeyType}}>.Default.Equals(__oldKey{{keyIndex}}, __newKey{{keyIndex}});
                            """);
        }

        static string EmitApplyKeyChange(TableModel model, int keyIndex)
        {
            var indexField = model.Keys[keyIndex].IndexField;
            return Render($$"""
                            if (__changed{{keyIndex}})
                            {
                                {{indexField}}.Remove(__oldKey{{keyIndex}}, primaryKey);
                                {{indexField}}.Insert(__newKey{{keyIndex}}, primaryKey);
                            }
                            """);
        }

        static string EmitRemove(TableModel model)
        {
            var removeFromIndexes = If(model.Keys.Count > 0, Render($$"""
                                                                      ref readonly var row = ref __store.GetRowRef(index);
                                                                      {{Each(model.Keys, key => $"{key.IndexField}.Remove({ConvertKey(key, "row." + key.Field.Name)}, primaryKey);")}}
                                                                      """));

            return Render($$"""
                            public bool Remove({{model.PrimaryKeyType}} primaryKey)
                            {
                                if (!__store.TryGetIndex(primaryKey, out var index)) return false;
                            
                                {{removeFromIndexes}}
                                __store.Remove(index);
                                return true;
                            }
                            """);
        }

        static string EmitKeyQueries(TableModel model, KeyModel key, string storeType)
        {
            var rowType = model.RowFullName;
            var fieldName = key.Field.Name;
            var fieldType = key.Field.Type;
            var indexField = key.IndexField;
            var enumerableType = $"{storeType}.SubsetEnumerable<{InnerEnumeratorType(model, key)}>";
            var findFirstMethod = key.Unique ? $"TryFindBy{fieldName}" : $"TryFindFirstBy{fieldName}";
            var findFirstPrimaryKeyMethod = key.Unique ? $"TryFindPrimaryKeyBy{fieldName}" : $"TryFindFirstPrimaryKeyBy{fieldName}";
            var findFirstRefMethod = key.Unique ? $"FindRefBy{fieldName}" : $"FindFirstRefBy{fieldName}";

            return Render($$"""
                            public bool {{findFirstMethod}}({{fieldType}} key, out {{rowType}} row)
                            {
                                if ({{indexField}}.TryGetFirst({{ConvertKey(key, "key")}}, out var primaryKey))
                                {
                                    row = __store.GetRowRef(__store.GetIndex(primaryKey));
                                    return true;
                                }
                            
                                row = default;
                                return false;
                            }

                            public ref readonly {{rowType}} {{findFirstRefMethod}}({{fieldType}} key, out bool found)
                            {
                                found = {{indexField}}.TryGetFirst({{ConvertKey(key, "key")}}, out var primaryKey);
                                if (found) return ref __store.GetRowRef(__store.GetIndex(primaryKey));
                                return ref __notFound;
                            }

                            public bool {{findFirstPrimaryKeyMethod}}({{fieldType}} key, out {{model.PrimaryKeyType}} primaryKey) => {{indexField}}.TryGetFirst({{ConvertKey(key, "key")}}, out primaryKey);

                            {{If(!key.Unique, $"public {enumerableType} FindAllBy{fieldName}({fieldType} key) => __store.Subset({indexField}.Equal({ConvertKey(key, "key")}));")}}

                            {{If(!key.Hash, $"public {enumerableType} FindRangeBy{fieldName}({fieldType} min, {fieldType} max) => __store.Subset({indexField}.Range({ConvertKey(key, "min")}, {ConvertKey(key, "max")}));")}}
                            """);
        }

        static string IndexType(TableModel model, KeyModel key)
        {
            if (!key.Hash) return $"global::OrdoMemory.OrderedIndex<{key.KeyType}, {key.KeyTraits}, {model.PrimaryKeyType}, {model.PrimaryKeyTraits}>";
            return key.Unique
                ? $"global::OrdoMemory.HashUniqueIndex<{key.KeyType}, {model.PrimaryKeyType}>"
                : $"global::OrdoMemory.HashMultiIndex<{key.KeyType}, {model.PrimaryKeyType}>";
        }

        static string IndexConstructorArguments(KeyModel key)
        {
            if (key.Hash) return "";
            return key.Unique ? "true" : "false";
        }

        static string InnerEnumeratorType(TableModel model, KeyModel key)
        {
            if (!key.Hash) return IndexType(model, key) + ".RangeEnumerator";
            return IndexType(model, key) + (key.Unique ? ".SingleEnumerator" : ".Enumerator");
        }

        static string ConvertKey(KeyModel key, string expression)
        {
            return string.Format(key.Convert, expression);
        }
    }
}
